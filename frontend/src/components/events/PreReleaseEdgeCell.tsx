import React from 'react';
import { Box, Button, Tooltip, Typography } from '@mui/material';
import { useThemeMode } from '../../theme/ThemeContext';
import { PreReleaseEdge, headline, fmtPct, fmtProb, isTradeVerdict } from './preReleaseTypes';

interface Props {
  edge?: PreReleaseEdge;
  upcomingDate?: string | null;
  onOpen: () => void;
}

export const PreReleaseEdgeCell: React.FC<Props> = ({ edge, upcomingDate, onOpen }) => {
  const { tokens } = useThemeMode();

  if (!edge) {
    return (
      <Tooltip title={upcomingDate ? 'Forecast is generated by the daily Pre-Release Edge job for results due in the next 30 days' : 'No results due in the next 30 days'} placement="top">
        <Box sx={{ display: 'flex', alignItems: 'center', height: '100%' }}>
          <Typography sx={{ fontSize: '11px', color: tokens.text.tertiary }}>{upcomingDate ? 'Forecast pending' : '—'}</Typography>
        </Box>
      </Tooltip>
    );
  }

  const green = tokens.status.success.main;
  const red = tokens.status.error.main;
  const muted = tokens.text.tertiary;

  let line1: React.ReactNode;
  let line2: string;
  let accent = muted;

  if (edge.graded) {
    const ret = edge.realizedTradeReturn ?? edge.realizedReaction3d;
    const scored = edge.hit != null;
    accent = !scored ? muted : edge.hit ? green : red;
    line1 = (
      <>
        <span style={{ color: accent }}>{!scored ? '•' : edge.hit ? '✓' : '✕'}</span>&nbsp;{fmtPct(ret)}
      </>
    );
    line2 = `RESULT · ${edge.verdict ?? 'NO EDGE'}`;
  } else {
    const h = headline(edge);
    const up = (h.p50 ?? 0) >= 0;
    const trade = isTradeVerdict(edge.verdict);
    accent = trade ? green : edge.verdict === 'AVOID' ? red : muted;
    line1 = (
      <>
        <span style={{ color: up ? green : red }}>{up ? '▲' : '▼'}</span>&nbsp;{fmtProb(edge.verdict === 'AVOID' ? 1 - (h.p ?? 0.5) : h.p)}
        <span style={{ color: tokens.text.secondary, fontWeight: 500 }}>&nbsp;·&nbsp;{fmtPct(h.p50)}</span>
      </>
    );
    const conf = trade || edge.verdict === 'AVOID' ? `${edge.confidence} · ` : '';
    line2 = `${conf}${edge.verdict}`;
  }

  const preliminary = !edge.graded && (edge.daysToEvent ?? 0) > 8;
  const when = edge.graded ? 'done' : edge.daysToEvent === 0 ? 'today' : `T-${edge.daysToEvent}d${preliminary ? ' · early' : ''}`;

  return (
    <Box sx={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', gap: 1, width: '100%', height: '100%' }}>
      <Tooltip title={preliminary ? 'Early read: the final call is made about 5 trading days before results, when the run-up window opens. It refreshes daily.' : ''} placement="top" disableHoverListener={!preliminary}>
      <Box onClick={(e) => { e.stopPropagation(); onOpen(); }} sx={{ display: 'flex', flexDirection: 'column', gap: '3px', minWidth: 0, cursor: 'pointer', opacity: preliminary && !isTradeVerdict(edge.verdict) && edge.verdict !== 'AVOID' ? 0.75 : 1 }}>
        <Typography className="mono-font tabular-nums" noWrap sx={{ fontSize: '13px', fontWeight: 700, color: tokens.text.primary, lineHeight: '16px' }}>
          {line1}
          <span style={{ color: muted, fontWeight: 500, fontSize: '10px' }}>&nbsp;&nbsp;{when}</span>
        </Typography>
        <Box sx={{ display: 'inline-flex', alignItems: 'center', gap: '4px', fontSize: '11px', fontWeight: 600, color: tokens.text.secondary, whiteSpace: 'nowrap' }}>
          <span style={{ color: accent, fontSize: '14px', lineHeight: 1 }}>•</span>
          <span style={{ overflow: 'hidden', textOverflow: 'ellipsis' }}>{line2}</span>
        </Box>
      </Box>
      </Tooltip>
      <Button
        size="small"
        onClick={(e) => { e.stopPropagation(); onOpen(); }}
        sx={{
          minWidth: 0, px: '10px', py: '3px', fontSize: '10px', fontWeight: 700, lineHeight: '16px', flexShrink: 0,
          color: tokens.text.primary, border: `1px solid ${isTradeVerdict(edge.verdict) && !edge.graded ? green : tokens.text.tertiary}`,
          borderRadius: '4px', textTransform: 'none',
          '&:hover': { borderColor: tokens.border.focus, backgroundColor: tokens.background.cardHover },
        }}
      >
        VIEW ↗
      </Button>
    </Box>
  );
};
